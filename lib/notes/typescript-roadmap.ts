import type {
  NoteCourse,
  NoteModule,
  NotePhase,
  NoteSection,
  ReviewSnapshot,
} from "@/lib/notes/types";

type SectionSeed = {
  title: string;
  topics?: string[];
};

function s(title: string, topics?: string[]): SectionSeed {
  return { title, topics };
}

const reviewedSectionIds = new Set([
  "ts-m01-s01",
  "ts-m01-s02",
  "ts-m01-s03",
]);

const incompleteSectionIds = new Set<string>([]);

function buildSections(moduleId: string, seeds: SectionSeed[]): NoteSection[] {
  return seeds.map((seed, index) => {
    const id = `${moduleId}-s${String(index + 1).padStart(2, "0")}`;
    const topics = seed.topics ?? [];
    return {
      id,
      title: seed.title,
      topics,
      status: reviewedSectionIds.has(id)
        ? "reviewed"
        : incompleteSectionIds.has(id)
          ? "incomplete"
          : "draft",
      minutes: Math.max(4, Math.ceil((seed.title.length + topics.join(" ").length) / 90)),
    };
  });
}

function mod(
  number: number,
  title: string,
  summary: string,
  seeds: SectionSeed[],
): NoteModule {
  const id = `ts-m${String(number).padStart(2, "0")}`;
  return {
    id,
    number: String(number).padStart(2, "0"),
    title,
    summary,
    kind: "module",
    sections: buildSections(id, seeds),
  };
}

function project(
  number: number,
  title: string,
  summary: string,
  seeds: SectionSeed[],
): NoteModule {
  const id = `ts-p${String(number).padStart(2, "0")}`;
  return {
    id,
    number: `P${String(number).padStart(2, "0")}`,
    title,
    summary,
    kind: "project",
    sections: buildSections(id, seeds),
  };
}

function phase(
  number: number,
  title: string,
  subtitle: string,
  summary: string,
  modules: NoteModule[],
): NotePhase {
  return {
    id: `ts-phase-${String(number).padStart(2, "0")}`,
    number,
    title,
    subtitle,
    summary,
    modules,
  };
}

